void fb_clear(void) { memset(fb, 0, sizeof(fb)); }

static void fb_draw_char(uint8_t x, uint8_t page, char c) {
    if (page >= OLED_PAGES) return;
    if (x > (OLED_W - 6)) return;
    if (c < 32 || c > 90) c = ' ';
    const uint8_t *gph = font6x8[(uint8_t)(c - 32)];
    for (int i = 0; i < 6; i++) fb[page][x + i] = gph[i];
}

void fb_draw_text(uint8_t x, uint8_t page, const char *s) {
    uint8_t cx = x;
    while (*s && cx <= (OLED_W - 6)) {
        fb_draw_char(cx, page, *s++);
        cx = (uint8_t)(cx + 6);
    }
}

const uint8_t *fb_pages_flattened(void) {
    return (const uint8_t *)&fb[0][0];
}

int fb_pages_count(void) { return OLED_PAGES; }
int fb_width(void) { return OLED_W; }